import { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import {
  FileCheck2,
  Send,
  Trash2,
  AlertCircle,
  ExternalLink,
  ShieldCheck,
  AlertTriangle,
  HelpCircle,
  CheckCircle2,
  XCircle,
  Download,
  Copy,
  Check,
  Lightbulb,
} from 'lucide-react';
import { verifyNews, downloadPdfReport } from '../services/api';
import LoadingSpinner from '../components/LoadingSpinner';
import { useLanguage } from '../hooks/useLanguage';

const SAMPLES = [
  {
    title: 'Viral Space / Science Claim',
    claim: 'NASA declared that Sanskrit is the most computer-friendly and error-free programming language in the world.',
  },
  {
    title: 'Medical Miracle Hoax',
    claim: 'Drinking warm lemon water with baking soda cures 100% of cancer tumors in 48 hours without chemotherapy.',
  },
  {
    title: 'Established Factual Event',
    claim: 'India successfully landed the Chandrayaan-3 mission spacecraft near the lunar south pole in August 2023.',
  },
];

export default function NewsVerification() {
  const { t } = useLanguage();
  const [claim, setClaim] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [result, setResult] = useState(null);
  const [copied, setCopied] = useState(false);
  const [downloading, setDownloading] = useState(false);

  const handleVerify = async () => {
    if (!claim.trim()) {
      setError(t.errors.emptyClaim);
      return;
    }

    setError('');
    setLoading(true);
    setResult(null);

    try {
      const data = await verifyNews(claim.trim());
      setResult(data);
    } catch (err) {
      console.error(err);
      const msg =
        err.response?.data?.detail ||
        (err.code === 'ERR_NETWORK' ? t.errors.network : t.errors.serverError);
      setError(msg);
    } finally {
      setLoading(false);
    }
  };

  const handleClear = () => {
    setClaim('');
    setError('');
    setResult(null);
  };

  const handleCopy = () => {
    if (!result) return;
    const text = `[TrustShield AI Fact-Check Verification Report]
Claim: "${result.claim}"
Verification Status: ${result.status}
Confidence Level: ${result.confidence_level}%
Explanation: ${result.explanation}

Sources:
${(result.sources || []).map((s) => `• ${s.name} (${s.url})`).join('\n')}

Recommendations:
${(result.recommendations || []).map((r) => `• ${r}`).join('\n')}

Generated by TrustShield AI — Digital Safety & Misinformation Defense.`;

    navigator.clipboard.writeText(text).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    });
  };

  const handleDownloadPdf = async () => {
    if (!result) return;
    setDownloading(true);
    try {
      await downloadPdfReport({
        report_type: 'news-factcheck',
        claim: result.claim,
        submitted_content: result.claim,
        risk_score: result.confidence_level,
        risk_level: result.status,
        status: result.status,
        summary: result.explanation,
        warning_signs: result.contradicting_evidence,
        supporting_evidence: result.supporting_evidence,
        recommendations: result.recommendations,
        sources: result.sources,
        scan_id: result.scan_id,
      });
    } catch (err) {
      console.error(err);
    } finally {
      setDownloading(false);
    }
  };

  const getStatusTheme = (status) => {
    switch (status) {
      case 'Supported by Evidence':
        return {
          bg: 'bg-emerald-500/10',
          border: 'border-emerald-500/30',
          text: 'text-emerald-400',
          badge: 'bg-emerald-500/20 text-emerald-300 border-emerald-500/40',
          icon: CheckCircle2,
        };
      case 'Disputed by Evidence':
        return {
          bg: 'bg-rose-500/10',
          border: 'border-rose-500/30',
          text: 'text-rose-400',
          badge: 'bg-rose-500/20 text-rose-300 border-rose-500/40',
          icon: XCircle,
        };
      case 'Misleading':
        return {
          bg: 'bg-amber-500/10',
          border: 'border-amber-500/30',
          text: 'text-amber-400',
          badge: 'bg-amber-500/20 text-amber-300 border-amber-500/40',
          icon: AlertTriangle,
        };
      default:
        return {
          bg: 'bg-indigo-500/10',
          border: 'border-indigo-500/30',
          text: 'text-indigo-400',
          badge: 'bg-indigo-500/20 text-indigo-300 border-indigo-500/40',
          icon: HelpCircle,
        };
    }
  };

  return (
    <div className="max-w-3xl mx-auto px-4 sm:px-6 lg:px-8 py-10 md:py-14 space-y-8">
      {/* Toast Notification */}
      <AnimatePresence>
        {copied && (
          <motion.div
            role="status"
            aria-live="polite"
            initial={{ opacity: 0, y: -20 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: -20 }}
            className="fixed top-20 right-6 z-50 flex items-center gap-2 bg-emerald-700 text-white px-4 py-2.5 rounded-xl shadow-xl border border-emerald-500/30 text-sm font-medium"
          >
            <Check className="w-4 h-4" aria-hidden="true" />
            {t.riskReport.copied}
          </motion.div>
        )}
      </AnimatePresence>

      {/* Page Header */}
      <header className="space-y-2">
        <div className="flex items-center gap-2 text-cyan-400 text-xs font-semibold uppercase tracking-widest">
          <FileCheck2 className="w-3.5 h-3.5" aria-hidden="true" />
          Claim Verification
        </div>
        <h1 className="text-3xl sm:text-4xl font-extrabold text-white tracking-tight">
          {t.newsVerification.title}
        </h1>
        <p className="text-slate-400 text-sm sm:text-base max-w-xl">
          Enter a news headline, viral forward, or factual claim. The system looks for
          publicly available evidence and indicates how well-supported or contested the claim
          appears. Results reflect available information — not a definitive verdict.
        </p>
      </header>

      {/* Input Section */}
      <div className="rounded-2xl bg-white/[0.03] border border-white/[0.08] p-6 md:p-8 space-y-5">
        <div>
          <label htmlFor="claim-input" className="block text-sm font-medium text-slate-200 mb-2">
            News headline or claim to verify
          </label>

          <textarea
            id="claim-input"
            rows={5}
            value={claim}
            onChange={(e) => {
              setClaim(e.target.value);
              if (error) setError('');
            }}
            placeholder={t.newsVerification.placeholder}
            aria-describedby="claim-hint"
            className="w-full rounded-xl bg-black/30 border border-white/[0.08] p-4 text-sm text-white placeholder-slate-600 focus:outline-none focus:border-cyan-500 focus:ring-1 focus:ring-cyan-500/40 transition font-sans leading-relaxed resize-y"
          />          <p id="claim-hint" className="mt-1.5 text-xs text-slate-500">
            Enter a specific claim or headline for best results. Vague queries may return uncertain results.
          </p>
        </div>

          {/* Quick Samples */}
          <div className="space-y-2 pt-1">
            <span className="flex items-center gap-1 text-[11px] uppercase tracking-wider font-semibold text-slate-500">
              <Lightbulb className="w-3 h-3 text-cyan-400/70" aria-hidden="true" />
              Try a demo claim
            </span>
            <div className="flex flex-wrap gap-2" role="group" aria-label="Demo claim examples">
              {SAMPLES.map((sample, idx) => (
                <button
                  key={idx}
                  type="button"
                  onClick={() => {
                    setClaim(sample.claim);
                    setError('');
                    setResult(null);
                  }}
                  className="text-xs px-3 py-1.5 rounded-lg bg-white/[0.04] hover:bg-white/[0.08] border border-white/[0.08] hover:border-cyan-500/30 text-slate-400 hover:text-cyan-300 transition text-left"
                >
                  {sample.title}
                </button>
              ))}
            </div>
          </div>

          {/* Error */}
          <AnimatePresence>
            {error && (
              <motion.div
                role="alert"
                initial={{ opacity: 0, y: -8 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0, y: -8 }}
                className="flex items-start gap-2.5 p-3.5 rounded-xl bg-rose-500/10 border border-rose-500/30 text-xs text-rose-300"
              >
                <AlertCircle className="w-4 h-4 text-rose-400 flex-shrink-0 mt-0.5" aria-hidden="true" />
                {error}
              </motion.div>
            )}
          </AnimatePresence>

          {/* Actions */}
          <div className="flex flex-col sm:flex-row items-center justify-between gap-3 pt-2 border-t border-white/[0.06]">
            <button
              type="button"
              onClick={handleClear}
              disabled={loading || (!claim && !result)}
              className="w-full sm:w-auto px-4 py-2.5 rounded-xl text-xs font-semibold text-slate-400 hover:text-white bg-white/[0.04] hover:bg-white/[0.08] border border-white/[0.08] transition disabled:opacity-40 disabled:cursor-not-allowed flex items-center justify-center gap-2"
            >
              <Trash2 className="w-4 h-4" aria-hidden="true" />
              {t.scamDetector.clear}
            </button>

            <button
              type="button"
              onClick={handleVerify}
              disabled={loading || !claim.trim()}
              className="w-full sm:w-auto px-7 py-3 rounded-xl text-sm font-bold text-white bg-cyan-600 hover:bg-cyan-500 shadow-md shadow-cyan-900/30 transition disabled:opacity-40 disabled:cursor-not-allowed flex items-center justify-center gap-2"
              aria-busy={loading}
            >
              {loading ? (
                <>
                  <span
                    className="w-4 h-4 border-2 border-white/30 border-t-white rounded-full motion-safe:animate-spin"
                    aria-hidden="true"
                  />
                  {t.newsVerification.verifying}
                </>
              ) : (
                <>
                  <Send className="w-4 h-4" aria-hidden="true" />
                  {t.newsVerification.verify}
                </>
              )}
            </button>
          </div>
        </div>

      {/* Loading state */}
      {loading && <LoadingSpinner text={t.newsVerification.verifying} />}

      {/* Verification Result Card */}
      {result && (
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          className="relative rounded-3xl bg-[#0d1635]/80 backdrop-blur-md border border-white/10 p-6 md:p-8 shadow-2xl shadow-black/50 space-y-6"
        >
          {(() => {
            const theme = getStatusTheme(result.status);
            const StatusIcon = theme.icon;

            return (
              <>
                {/* Result Header */}
                <div className="flex flex-col md:flex-row items-center justify-between gap-6 pb-6 border-b border-white/10">
                  <div className="flex flex-col sm:flex-row items-center gap-5 text-center sm:text-left">
                    <div className={`w-16 h-16 rounded-2xl ${theme.bg} border ${theme.border} flex items-center justify-center ${theme.text}`}>
                      <StatusIcon className="w-8 h-8" />
                    </div>
                    <div>
                      <div className="flex items-center justify-center sm:justify-start gap-2 mb-1.5">
                        <span className={`inline-flex items-center gap-1 px-3 py-1 rounded-full text-xs font-bold uppercase tracking-wider border ${theme.badge}`}>
                          {result.status}
                        </span>
                        <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-white/5 text-slate-400 border border-white/10">
                          Confidence: {result.confidence_level}%
                        </span>
                      </div>
                      <h2 className="text-lg md:text-xl font-bold text-white max-w-xl">
                        "{result.claim}"
                      </h2>
                    </div>
                  </div>

                  {/* Actions */}
                  <div className="flex flex-wrap items-center gap-2">
                    <button
                      onClick={handleCopy}
                      className="flex items-center space-x-1.5 px-3 py-2 rounded-xl bg-white/5 hover:bg-white/10 border border-white/10 text-xs font-medium text-slate-200 transition"
                    >
                      <Copy className="w-3.5 h-3.5 text-cyan-400" />
                      <span>{t.riskReport.copyReport}</span>
                    </button>
                    <button
                      onClick={handleDownloadPdf}
                      disabled={downloading}
                      className="flex items-center space-x-1.5 px-3 py-2 rounded-xl bg-cyan-500/10 hover:bg-cyan-500/20 border border-cyan-500/30 text-xs font-medium text-cyan-300 transition disabled:opacity-50"
                    >
                      <Download className="w-3.5 h-3.5 text-cyan-400" />
                      <span>{downloading ? '...' : t.riskReport.downloadPdf}</span>
                    </button>
                  </div>
                </div>

                {/* Explanation */}
                <div className="py-2">
                  <h3 className="text-xs font-semibold text-slate-300 uppercase tracking-wider mb-2">
                    Assessment
                  </h3>
                  <p className="text-sm text-slate-300 leading-relaxed bg-white/[0.02] p-4 rounded-xl border border-white/5">
                    {result.explanation}
                  </p>
                  <p className="mt-2 text-[11px] text-slate-500 leading-relaxed">
                    This assessment is based on pattern matching and publicly available references.
                    It is not a substitute for journalism or independent fact-checking. Confidence
                    scores reflect available evidence, not certainty.
                  </p>
                </div>

                {/* Evidence Grid: Supporting & Contradicting */}
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  {/* Supporting Evidence */}
                  <div className="p-4 rounded-xl bg-emerald-500/[0.05] border border-emerald-500/20 space-y-2">
                    <h4 className="text-xs font-semibold uppercase tracking-wider text-emerald-400 flex items-center gap-1.5">
                      <CheckCircle2 className="w-4 h-4" />
                      <span>{t.newsVerification.supporting}</span>
                    </h4>
                    <ul className="space-y-1.5 text-xs text-slate-300">
                      {result.supporting_evidence?.map((item, i) => (
                        <li key={i} className="flex items-start gap-2">
                          <span className="text-emerald-400 font-bold">•</span>
                          <span>{item}</span>
                        </li>
                      ))}
                    </ul>
                  </div>

                  {/* Contradicting / Discrepancies */}
                  <div className="p-4 rounded-xl bg-rose-500/[0.05] border border-rose-500/20 space-y-2">
                    <h4 className="text-xs font-semibold uppercase tracking-wider text-rose-400 flex items-center gap-1.5">
                      <AlertTriangle className="w-4 h-4" />
                      <span>{t.newsVerification.contradicting}</span>
                    </h4>
                    <ul className="space-y-1.5 text-xs text-slate-300">
                      {result.contradicting_evidence?.map((item, i) => (
                        <li key={i} className="flex items-start gap-2">
                          <span className="text-rose-400 font-bold">•</span>
                          <span>{item}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                </div>

                {/* Real Sources and Links */}
                {result.sources && result.sources.length > 0 && (
                  <div className="pt-2">
                    <h3 className="text-xs font-semibold text-slate-300 uppercase tracking-wider mb-3">
                      {t.newsVerification.sources}
                    </h3>
                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                      {result.sources.map((s, idx) => (
                        <a
                          key={idx}
                          href={s.url}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="p-3.5 rounded-xl bg-white/[0.03] hover:bg-white/[0.07] border border-white/10 hover:border-cyan-500/40 transition group block"
                        >
                          <div className="flex items-center justify-between text-xs font-semibold text-white group-hover:text-cyan-300 mb-1">
                            <span className="truncate">{s.name}</span>
                            <ExternalLink className="w-3.5 h-3.5 text-slate-400 group-hover:text-cyan-400 flex-shrink-0 ml-2" />
                          </div>
                          {s.snippet && (
                            <p className="text-[11px] text-slate-400 line-clamp-2 leading-relaxed">
                              {s.snippet}
                            </p>
                          )}
                          <span className="text-[10px] text-cyan-400/80 font-mono mt-1.5 block truncate">
                            {s.url}
                          </span>
                        </a>
                      ))}
                    </div>
                  </div>
                )}

                {/* Recommended Safety Actions */}
                {result.recommendations && result.recommendations.length > 0 && (
                  <div className="pt-2">
                    <h3 className="text-xs font-semibold text-slate-300 uppercase tracking-wider mb-3 flex items-center gap-1.5">
                      <ShieldCheck className="w-3.5 h-3.5 text-cyan-400" />
                      <span>Recommended Next Steps &amp; Media Literacy</span>
                    </h3>
                    <div className="space-y-2">
                      {result.recommendations.map((rec, i) => (
                        <div key={i} className="flex items-start space-x-2.5 p-3 rounded-xl bg-white/[0.02] border border-white/5 text-xs text-slate-300">
                          <span className="w-4 h-4 rounded-full bg-cyan-500/20 text-cyan-400 flex items-center justify-center flex-shrink-0 text-[10px] font-bold">
                            {i + 1}
                          </span>
                          <span>{rec}</span>
                        </div>
                      ))}
                    </div>
                  </div>
                )}
              </>
            );
          })()}
        </motion.div>
      )}
    </div>
  );
}

