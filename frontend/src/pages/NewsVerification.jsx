import { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import {
  FileCheck2,
  Send,
  Trash2,
  AlertCircle,
  ExternalLink,
  ShieldCheck,
  AlertTriangle,
  HelpCircle,
  CheckCircle2,
  XCircle,
  Download,
  Copy,
  Check,
  Lightbulb,
} from 'lucide-react';
import { verifyNews, downloadPdfReport } from '../services/api';
import LoadingSpinner from '../components/LoadingSpinner';
import { useLanguage } from '../hooks/useLanguage';

const SAMPLES = [
  {
    title: 'Viral Space / Science Claim',
    claim: 'NASA declared that Sanskrit is the most computer-friendly and error-free programming language in the world.',
  },
  {
    title: 'Medical Miracle Hoax',
    claim: 'Drinking warm lemon water with baking soda cures 100% of cancer tumors in 48 hours without chemotherapy.',
  },
  {
    title: 'Established Factual Event',
    claim: 'India successfully landed the Chandrayaan-3 mission spacecraft near the lunar south pole in August 2023.',
  },
];

export default function NewsVerification() {
  const { t } = useLanguage();
  const [claim, setClaim] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [result, setResult] = useState(null);
  const [copied, setCopied] = useState(false);
  const [downloading, setDownloading] = useState(false);

  const handleVerify = async () => {
    if (!claim.trim()) {
      setError(t.errors.emptyClaim);
      return;
    }

    setError('');
    setLoading(true);
    setResult(null);

    try {
      const data = await verifyNews(claim.trim());
      setResult(data);
    } catch (err) {
      console.error(err);
      const msg =
        err.response?.data?.detail ||
        (err.isConfigurationError || err.code === 'ERR_NETWORK' || !err.response
          ? 'Unable to connect to TrustShield backend API. Please verify the backend service is running and VITE_API_URL is configured.'
          : err.message || t.errors.serverError);
      setError(msg);
    } finally {
      setLoading(false);
    }
  };

  const handleClear = () => {
    setClaim('');
    setError('');
    setResult(null);
  };

  const handleCopy = () => {
    if (!result) return;
    const text = `[TrustShield AI Fact-Check Report]
Claim: "${result.claim}"
Verification Status: ${result.status}
Confidence Level: ${result.confidence_level}%
Explanation: ${result.explanation}

Sources:
${(result.sources || []).map((s) => `• ${s.name} (${s.url})`).join('\n')}

Recommendations:
${(result.recommendations || []).map((r) => `• ${r}`).join('\n')}

Generated by TrustShield AI — Stay Safe Online.`;

    navigator.clipboard.writeText(text).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    });
  };

  const handleDownloadPdf = async () => {
    if (!result) return;
    setDownloading(true);
    try {
      await downloadPdfReport({
        report_type: 'news-factcheck',
        claim: result.claim,
        submitted_content: result.claim,
        risk_score: result.confidence_level,
        risk_level: result.status,
        status: result.status,
        summary: result.explanation,
        warning_signs: result.contradicting_evidence,
        supporting_evidence: result.supporting_evidence,
        recommendations: result.recommendations,
        sources: result.sources,
        scan_id: result.scan_id,
      });
    } catch (err) {
      console.error(err);
    } finally {
      setDownloading(false);
    }
  };

  const getStatusTheme = (status) => {
    switch (status) {
      case 'Supported by Evidence':
        return {
          bg: 'bg-emerald-50',
          border: 'border-emerald-200',
          text: 'text-emerald-700',
          badge: 'bg-emerald-100 text-emerald-800 border-emerald-300',
          icon: CheckCircle2,
        };
      case 'Disputed by Evidence':
        return {
          bg: 'bg-rose-50',
          border: 'border-rose-200',
          text: 'text-rose-700',
          badge: 'bg-rose-100 text-rose-800 border-rose-300',
          icon: XCircle,
        };
      case 'Misleading':
        return {
          bg: 'bg-amber-50',
          border: 'border-amber-200',
          text: 'text-amber-700',
          badge: 'bg-amber-100 text-amber-800 border-amber-300',
          icon: AlertTriangle,
        };
      default:
        return {
          bg: 'bg-teal-50',
          border: 'border-teal-200',
          text: 'text-[#0d766e]',
          badge: 'bg-teal-100 text-teal-800 border-teal-300',
          icon: HelpCircle,
        };
    }
  };

  return (
    <div className="max-w-3xl mx-auto px-4 sm:px-6 lg:px-8 py-10 md:py-14 space-y-8">
      {/* Toast */}
      <AnimatePresence>
        {copied && (
          <motion.div
            role="status"
            aria-live="polite"
            initial={{ opacity: 0, y: -20 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: -20 }}
            className="fixed top-20 right-6 z-50 flex items-center gap-2 bg-emerald-700 text-white px-4 py-2.5 rounded-xl shadow-xl text-sm font-medium"
          >
            <Check className="w-4 h-4" aria-hidden="true" />
            <span>Copied to clipboard!</span>
          </motion.div>
        )}
      </AnimatePresence>

      {/* Page Header */}
      <header className="space-y-2">
        <div className="flex items-center gap-2 text-[#0d766e] text-xs font-bold uppercase tracking-wider">
          <FileCheck2 className="w-4 h-4" aria-hidden="true" />
          <span>News Claim Verifier</span>
        </div>
        <h1 className="text-3xl sm:text-4xl font-extrabold text-slate-900 tracking-tight">
          Verify a News Headline or Viral Claim
        </h1>
        <p className="text-slate-600 text-sm sm:text-base max-w-xl">
          Enter a news story, social media rumor, or viral forward. We compare the claim
          against available evidence and credible references.
        </p>
      </header>

      {/* Input Section */}
      <div className="rounded-3xl bg-white border border-slate-200/90 p-6 md:p-8 shadow-xl shadow-slate-200/40 space-y-5">
        <div>
          <label htmlFor="claim-input" className="block text-sm font-bold text-slate-800 mb-2">
            News headline or claim to check
          </label>

          <textarea
            id="claim-input"
            rows={5}
            value={claim}
            onChange={(e) => {
              setClaim(e.target.value);
              if (error) setError('');
            }}
            placeholder="Paste news claim or headline here..."
            className="w-full rounded-2xl bg-slate-50 border border-slate-200 p-4 text-sm text-slate-900 placeholder-slate-400 focus:outline-none focus:bg-white focus:border-[#0d766e] focus:ring-1 focus:ring-[#0d766e]/30 transition leading-relaxed resize-y"
          />
        </div>

        {/* Quick Samples */}
        <div className="space-y-2">
          <span className="flex items-center gap-1.5 text-xs font-bold uppercase tracking-wider text-slate-500">
            <Lightbulb className="w-3.5 h-3.5 text-amber-500" aria-hidden="true" />
            Try a sample claim
          </span>
          <div className="flex flex-wrap gap-2">
            {SAMPLES.map((sample, idx) => (
              <button
                key={idx}
                type="button"
                onClick={() => {
                  setClaim(sample.claim);
                  setError('');
                  setResult(null);
                }}
                className="text-xs px-3 py-1.5 rounded-lg bg-slate-100 hover:bg-slate-200 border border-slate-200 text-slate-700 font-medium transition cursor-pointer text-left"
              >
                {sample.title}
              </button>
            ))}
          </div>
        </div>

        {/* Error */}
        <AnimatePresence>
          {error && (
            <motion.div
              role="alert"
              initial={{ opacity: 0, y: -8 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0, y: -8 }}
              className="flex items-start gap-2.5 p-3.5 rounded-xl bg-rose-50 border border-rose-200 text-xs text-rose-800"
            >
              <AlertCircle className="w-4 h-4 text-rose-600 flex-shrink-0 mt-0.5" aria-hidden="true" />
              <span>{error}</span>
            </motion.div>
          )}
        </AnimatePresence>

        {/* Actions */}
        <div className="flex flex-col sm:flex-row items-center justify-between gap-3 pt-3 border-t border-slate-100">
          <button
            type="button"
            onClick={handleClear}
            disabled={loading || (!claim && !result)}
            className="w-full sm:w-auto px-4 py-2.5 rounded-xl text-xs font-semibold text-slate-600 hover:text-slate-900 bg-slate-100 hover:bg-slate-200 border border-slate-200 transition disabled:opacity-40 disabled:cursor-not-allowed flex items-center justify-center gap-1.5 cursor-pointer"
          >
            <Trash2 className="w-3.5 h-3.5" aria-hidden="true" />
            <span>Clear</span>
          </button>

          <button
            type="button"
            onClick={handleVerify}
            disabled={loading || !claim.trim()}
            className="w-full sm:w-auto px-7 py-3 rounded-xl text-sm font-bold text-white bg-[#0d766e] hover:bg-[#0f766e] shadow-sm transition disabled:opacity-40 disabled:cursor-not-allowed flex items-center justify-center gap-2 cursor-pointer"
            aria-busy={loading}
          >
            {loading ? (
              <>
                <span className="w-4 h-4 border-2 border-white/30 border-t-white rounded-full animate-spin" />
                <span>Checking references...</span>
              </>
            ) : (
              <>
                <Send className="w-4 h-4" aria-hidden="true" />
                <span>Verify Claim</span>
              </>
            )}
          </button>
        </div>
      </div>

      {loading && <LoadingSpinner text="Searching references & evidence..." />}

      {/* Result Card */}
      {result && (
        <motion.div
          initial={{ opacity: 0, y: 16 }}
          animate={{ opacity: 1, y: 0 }}
          className="rounded-3xl bg-white border border-slate-200 p-6 md:p-8 shadow-xl shadow-slate-200/50 space-y-6"
        >
          {(() => {
            const theme = getStatusTheme(result.status);
            const StatusIcon = theme.icon;

            return (
              <>
                <div className="flex flex-col md:flex-row items-center justify-between gap-6 pb-6 border-b border-slate-100">
                  <div className="flex flex-col sm:flex-row items-center gap-5 text-center sm:text-left">
                    <div className={`w-14 h-14 rounded-2xl ${theme.bg} border ${theme.border} flex items-center justify-center ${theme.text}`}>
                      <StatusIcon className="w-7 h-7" />
                    </div>
                    <div>
                      <div className="flex items-center justify-center sm:justify-start gap-2 mb-1.5">
                        <span className={`inline-flex items-center gap-1 px-3 py-1 rounded-full text-xs font-bold uppercase tracking-wider border ${theme.badge}`}>
                          {result.status}
                        </span>
                        <span className="text-xs font-mono px-2 py-0.5 rounded bg-slate-100 text-slate-500">
                          Confidence: {result.confidence_level}%
                        </span>
                      </div>
                      <h2 className="text-lg md:text-xl font-bold text-slate-900 max-w-xl">
                        "{result.claim}"
                      </h2>
                    </div>
                  </div>

                  <div className="flex items-center gap-2">
                    <button
                      onClick={handleCopy}
                      className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-slate-50 hover:bg-slate-100 border border-slate-200 text-xs font-semibold text-slate-700 transition"
                    >
                      <Copy className="w-3.5 h-3.5 text-[#0d766e]" />
                      <span>Copy</span>
                    </button>
                    <button
                      onClick={handleDownloadPdf}
                      disabled={downloading}
                      className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-teal-50 hover:bg-teal-100 border border-teal-200 text-xs font-semibold text-[#0d766e] transition disabled:opacity-50"
                    >
                      <Download className="w-3.5 h-3.5 text-[#0d766e]" />
                      <span>{downloading ? '...' : 'PDF'}</span>
                    </button>
                  </div>
                </div>

                {/* Explanation */}
                <div className="py-2">
                  <h3 className="text-xs font-bold text-slate-900 uppercase tracking-wider mb-2">
                    Assessment
                  </h3>
                  <p className="text-sm text-slate-700 leading-relaxed bg-slate-50 p-4 rounded-xl border border-slate-100">
                    {result.explanation}
                  </p>
                </div>

                {/* Evidence Grid */}
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  <div className="p-4 rounded-xl bg-emerald-50/60 border border-emerald-200 space-y-2">
                    <h4 className="text-xs font-bold uppercase tracking-wider text-emerald-800 flex items-center gap-1.5">
                      <CheckCircle2 className="w-4 h-4 text-emerald-600" />
                      <span>Supporting Evidence</span>
                    </h4>
                    <ul className="space-y-1.5 text-xs text-slate-700">
                      {result.supporting_evidence?.map((item, i) => (
                        <li key={i} className="flex items-start gap-2">
                          <span className="text-emerald-600 font-bold">•</span>
                          <span>{item}</span>
                        </li>
                      ))}
                    </ul>
                  </div>

                  <div className="p-4 rounded-xl bg-rose-50/60 border border-rose-200 space-y-2">
                    <h4 className="text-xs font-bold uppercase tracking-wider text-rose-800 flex items-center gap-1.5">
                      <AlertTriangle className="w-4 h-4 text-rose-600" />
                      <span>Contradicting Evidence</span>
                    </h4>
                    <ul className="space-y-1.5 text-xs text-slate-700">
                      {result.contradicting_evidence?.map((item, i) => (
                        <li key={i} className="flex items-start gap-2">
                          <span className="text-rose-600 font-bold">•</span>
                          <span>{item}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                </div>

                {/* Sources */}
                {result.sources && result.sources.length > 0 && (
                  <div className="pt-2">
                    <h3 className="text-xs font-bold text-slate-900 uppercase tracking-wider mb-3">
                      Credible Sources &amp; References
                    </h3>
                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                      {result.sources.map((s, idx) => (
                        <a
                          key={idx}
                          href={s.url}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="p-3.5 rounded-xl bg-slate-50 hover:bg-slate-100 border border-slate-200 transition group block"
                        >
                          <div className="flex items-center justify-between text-xs font-bold text-slate-900 group-hover:text-[#0d766e] mb-1">
                            <span className="truncate">{s.name}</span>
                            <ExternalLink className="w-3.5 h-3.5 text-slate-400 group-hover:text-[#0d766e] ml-2" />
                          </div>
                          {s.snippet && (
                            <p className="text-[11px] text-slate-500 line-clamp-2">
                              {s.snippet}
                            </p>
                          )}
                        </a>
                      ))}
                    </div>
                  </div>
                )}
              </>
            );
          })()}
        </motion.div>
      )}
    </div>
  );
}
