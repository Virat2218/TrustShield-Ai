import { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import {
  ShieldAlert,
  ShieldCheck,
  AlertTriangle,
  Lock,
  Unlock,
  Globe,
  Copy,
  Check,
  RotateCcw,
  AlertOctagon,
  Info,
  ExternalLink,
  Download,
} from 'lucide-react';
import { useLanguage } from '../hooks/useLanguage';
import { downloadPdfReport } from '../services/api';

export default function RiskReport({ result, type = 'message', onReset, submittedContent = '' }) {
  const { t } = useLanguage();
  const [copied, setCopied] = useState(false);
  const [downloading, setDownloading] = useState(false);

  if (!result) return null;

  const score = result.risk_score ?? 0;
  const level = (result.risk_level || 'low').toLowerCase();

  // Color mappings
  const colorMap = {
    low: {
      text: 'text-emerald-400',
      bg: 'bg-emerald-500/10',
      border: 'border-emerald-500/30',
      glow: 'shadow-emerald-500/20',
      badge: 'bg-emerald-500/20 text-emerald-300 border-emerald-500/40',
      stroke: '#10b981',
      icon: ShieldCheck,
      label: t.riskReport.low,
    },
    medium: {
      text: 'text-amber-400',
      bg: 'bg-amber-500/10',
      border: 'border-amber-500/30',
      glow: 'shadow-amber-500/20',
      badge: 'bg-amber-500/20 text-amber-300 border-amber-500/40',
      stroke: '#f59e0b',
      icon: AlertTriangle,
      label: t.riskReport.medium,
    },
    high: {
      text: 'text-rose-400',
      bg: 'bg-rose-500/10',
      border: 'border-rose-500/30',
      glow: 'shadow-rose-500/20',
      badge: 'bg-rose-500/20 text-rose-300 border-rose-500/40',
      stroke: '#f43f5e',
      icon: ShieldAlert,
      label: t.riskReport.high,
    },
  };

  const currentTheme = colorMap[level] || colorMap.low;
  const LevelIcon = currentTheme.icon;

  // Circular gauge calculations
  const radius = 54;
  const circumference = 2 * Math.PI * radius;
  const strokeDashoffset = circumference - (score / 100) * circumference;

  const handleCopy = () => {
    const reportText = `[TrustShield AI Security Report]
Type: ${type.toUpperCase()}
Risk Score: ${score}/100 (${currentTheme.label})
Summary: ${result.summary || 'N/A'}
Warning Signs:
${(result.warning_signs || []).map((w) => `• ${w}`).join('\n')}
Recommendations:
${(result.recommendations || []).map((r) => `• ${r}`).join('\n')}

Generated by TrustShield AI — Stay Safe in the Digital World.`;

    navigator.clipboard.writeText(reportText).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    });
  };

  const handleDownloadPdf = async () => {
    setDownloading(true);
    try {
      await downloadPdfReport({
        report_type: type,
        submitted_content: submittedContent || result.domain || result.extracted_text || result.summary || 'Security Evaluation',
        risk_score: score,
        risk_level: currentTheme.label,
        summary: result.summary,
        warning_signs: result.warning_signs,
        recommendations: result.recommendations,
        domain: result.domain,
        https_status: result.https_status,
        scan_id: result.scan_id,
      });
    } catch (err) {
      console.error('PDF download error:', err);
    } finally {
      setDownloading(false);
    }
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.4 }}
      className="w-full space-y-6"
    >
      {/* Toast Notification */}
      <AnimatePresence>
        {copied && (
          <motion.div
            initial={{ opacity: 0, y: -20 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: -20 }}
            className="fixed top-20 right-6 z-50 flex items-center space-x-2 bg-emerald-600 text-white px-4 py-2.5 rounded-xl shadow-xl border border-emerald-400/30 text-sm font-medium"
          >
            <Check className="w-4 h-4" />
            <span>{t.riskReport.copied}</span>
          </motion.div>
        )}
      </AnimatePresence>

      {/* Main Card */}
      <div className="relative rounded-3xl bg-[#0d1635]/80 backdrop-blur-md border border-white/10 p-6 md:p-8 shadow-2xl shadow-black/50 overflow-hidden">
        {/* Glow backdrop */}
        <div
          className={`absolute top-0 right-0 w-80 h-80 rounded-full blur-3xl opacity-20 pointer-events-none ${
            level === 'high' ? 'bg-rose-500' : level === 'medium' ? 'bg-amber-500' : 'bg-emerald-500'
          }`}
        ></div>

        {/* Header with Circular Score & Risk Level */}
        <div className="flex flex-col md:flex-row items-center justify-between gap-6 pb-6 border-b border-white/10">
          <div className="flex flex-col sm:flex-row items-center gap-6 text-center sm:text-left">
            {/* SVG Circular Progress Gauge */}
            <div className="relative w-32 h-32 flex-shrink-0 flex items-center justify-center">
              <svg className="w-full h-full transform -rotate-90" viewBox="0 0 128 128">
                {/* Background Track */}
                <circle
                  cx="64"
                  cy="64"
                  r={radius}
                  stroke="#1e293b"
                  strokeWidth="10"
                  fill="transparent"
                />
                {/* Animated Progress Circle */}
                <motion.circle
                  cx="64"
                  cy="64"
                  r={radius}
                  stroke={currentTheme.stroke}
                  strokeWidth="10"
                  strokeLinecap="round"
                  fill="transparent"
                  strokeDasharray={circumference}
                  initial={{ strokeDashoffset: circumference }}
                  animate={{ strokeDashoffset }}
                  transition={{ duration: 1.2, ease: 'easeOut' }}
                />
              </svg>
              <div className="absolute inset-0 flex flex-col items-center justify-center">
                <span className="text-3xl font-extrabold text-white tracking-tight">{score}</span>
                <span className="text-[11px] text-slate-400 font-medium">/ 100</span>
              </div>
            </div>

            <div>
              <div className="flex items-center justify-center sm:justify-start gap-2 mb-2">
                <span
                  className={`inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-bold uppercase tracking-wider border ${currentTheme.badge}`}
                >
                  <LevelIcon className="w-4 h-4" />
                  {currentTheme.label}
                </span>
                {result.analysis_mode && (
                  <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-white/5 text-slate-400 border border-white/10 uppercase">
                    {result.analysis_mode}
                  </span>
                )}
              </div>
              <h2 className="text-xl md:text-2xl font-bold text-white mb-1">
                {t.riskReport.riskScore}: <span className={currentTheme.text}>{score}/100</span>
              </h2>
              <p className="text-xs text-slate-400 max-w-sm">
                {level === 'high'
                  ? 'High probability of malicious intent. Do not proceed.'
                  : level === 'medium'
                  ? 'Potential risk indicators detected. Proceed with caution.'
                  : 'Low risk score. Always practice caution with sensitive info.'}
              </p>
            </div>
          </div>

          {/* Action buttons */}
          <div className="flex flex-wrap items-center gap-2.5">
            <button
              onClick={handleCopy}
              className="flex items-center space-x-1.5 px-3.5 py-2 rounded-xl bg-white/5 hover:bg-white/10 border border-white/10 text-xs font-medium text-slate-200 transition"
              title="Copy analysis report"
            >
              <Copy className="w-3.5 h-3.5 text-cyan-400" />
              <span>{t.riskReport.copyReport}</span>
            </button>
            <button
              onClick={handleDownloadPdf}
              disabled={downloading}
              className="flex items-center space-x-1.5 px-3.5 py-2 rounded-xl bg-cyan-500/10 hover:bg-cyan-500/20 border border-cyan-500/30 text-xs font-medium text-cyan-300 transition disabled:opacity-50"
              title="Download official PDF report"
            >
              <Download className="w-3.5 h-3.5 text-cyan-400" />
              <span>{downloading ? 'Generating...' : t.riskReport.downloadPdf}</span>
            </button>
            <button
              onClick={onReset}
              className="flex items-center space-x-1.5 px-3.5 py-2 rounded-xl bg-blue-600/30 hover:bg-blue-600/50 border border-blue-500/40 text-xs font-medium text-cyan-200 transition"
            >
              <RotateCcw className="w-3.5 h-3.5" />
              <span>{t.riskReport.analyzeAnother}</span>
            </button>
          </div>
        </div>

        {/* URL Specific: Domain, HTTPS, and Safe Browsing indicator */}
        {type === 'url' && result.domain && (
          <div className="py-4 border-b border-white/10 grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
            <div className="flex items-center space-x-3 p-3 rounded-xl bg-white/[0.03] border border-white/5">
              <Globe className="w-5 h-5 text-cyan-400 flex-shrink-0" />
              <div className="min-w-0 flex-1">
                <span className="text-[11px] text-slate-400 block">{t.riskReport.domain}</span>
                <span className="text-sm font-semibold text-white truncate block">
                  {result.domain}
                </span>
              </div>
            </div>

            <div className="flex items-center space-x-3 p-3 rounded-xl bg-white/[0.03] border border-white/5">
              {result.https_status ? (
                <Lock className="w-5 h-5 text-emerald-400 flex-shrink-0" />
              ) : (
                <Unlock className="w-5 h-5 text-rose-400 flex-shrink-0" />
              )}
              <div className="min-w-0 flex-1">
                <span className="text-[11px] text-slate-400 block">{t.riskReport.httpsStatus}</span>
                <span
                  className={`text-sm font-semibold ${
                    result.https_status ? 'text-emerald-400' : 'text-rose-400'
                  }`}
                >
                  {result.https_status ? t.riskReport.secure : t.riskReport.notSecure}
                </span>
                <span className="text-[10px] text-slate-500 block">
                  (Note: HTTPS alone does not guarantee a site is safe)
                </span>
              </div>
            </div>

            {result.safe_browsing && (
              <div className="flex items-center space-x-3 p-3 rounded-xl bg-white/[0.03] border border-white/5 sm:col-span-2 lg:col-span-1">
                {result.safe_browsing.status === 'threat_found' ? (
                  <ShieldAlert className="w-5 h-5 text-rose-400 flex-shrink-0" />
                ) : result.safe_browsing.status === 'no_matches' ? (
                  <ShieldCheck className="w-5 h-5 text-emerald-400 flex-shrink-0" />
                ) : result.safe_browsing.status === 'api_error' ? (
                  <AlertTriangle className="w-5 h-5 text-amber-400 flex-shrink-0" />
                ) : (
                  <Info className="w-5 h-5 text-slate-400 flex-shrink-0" />
                )}
                <div className="min-w-0 flex-1">
                  <span className="text-[11px] text-slate-400 block">Google Safe Browsing</span>
                  <span
                    className={`text-sm font-semibold truncate block ${
                      result.safe_browsing.status === 'threat_found'
                        ? 'text-rose-400'
                        : result.safe_browsing.status === 'no_matches'
                        ? 'text-emerald-400'
                        : result.safe_browsing.status === 'api_error'
                        ? 'text-amber-400'
                        : 'text-slate-400'
                    }`}
                  >
                    {result.safe_browsing.status === 'threat_found'
                      ? 'Threat Flagged'
                      : result.safe_browsing.status === 'no_matches'
                      ? 'No Threat Matches'
                      : result.safe_browsing.status === 'api_error'
                      ? 'Check Unavailable'
                      : 'Not Configured'}
                  </span>
                  <span className="text-[10px] text-slate-500 block truncate" title={result.safe_browsing.details}>
                    {result.safe_browsing.status === 'threat_found'
                      ? (result.safe_browsing.threats || []).join(', ') || 'Known malicious site'
                      : result.safe_browsing.status === 'no_matches'
                      ? 'External database clear'
                      : result.safe_browsing.status === 'api_error'
                      ? 'External check did not complete'
                      : 'Structural heuristics only'}
                  </span>
                </div>
              </div>
            )}
          </div>
        )}

        {/* Summary */}
        <div className="py-5 border-b border-white/10">
          <h3 className="text-xs font-semibold text-slate-300 uppercase tracking-wider mb-2 flex items-center gap-2">
            <Info className="w-3.5 h-3.5 text-cyan-400" />
            {t.riskReport.summary}
          </h3>
          <p className="text-sm text-slate-300 leading-relaxed bg-white/[0.02] p-4 rounded-xl border border-white/5">
            {result.summary}
          </p>
        </div>

        {/* Warning Signs */}
        {result.warning_signs && result.warning_signs.length > 0 && (
          <div className="py-5 border-b border-white/10">
            <h3 className="text-xs font-semibold text-slate-300 uppercase tracking-wider mb-3 flex items-center gap-2">
              <AlertOctagon className="w-3.5 h-3.5 text-amber-400" />
              {t.riskReport.warningSigns}
            </h3>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
              {result.warning_signs.map((sign, idx) => (
                <div
                  key={idx}
                  className="flex items-start space-x-2.5 p-3 rounded-xl bg-amber-500/[0.07] border border-amber-500/20 text-xs text-amber-200"
                >
                  <AlertTriangle className="w-4 h-4 text-amber-400 flex-shrink-0 mt-0.5" />
                  <span>{sign}</span>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Highlighted Suspicious Phrases (messages only) */}
        {result.suspicious_phrases && result.suspicious_phrases.length > 0 && (
          <div className="py-5 border-b border-white/10">
            <h3 className="text-xs font-semibold text-slate-300 uppercase tracking-wider mb-3">
              {t.riskReport.suspicious}
            </h3>
            <div className="flex flex-wrap gap-2">
              {result.suspicious_phrases.map((phrase, idx) => (
                <span
                  key={idx}
                  className="inline-flex items-center px-3 py-1 rounded-lg text-xs font-mono bg-rose-500/10 border border-rose-500/30 text-rose-300"
                >
                  "{phrase}"
                </span>
              ))}
            </div>
          </div>
        )}

        {/* Recommendations */}
        {result.recommendations && result.recommendations.length > 0 && (
          <div className="pt-5">
            <h3 className="text-xs font-semibold text-slate-300 uppercase tracking-wider mb-3 flex items-center gap-2">
              <ShieldCheck className="w-3.5 h-3.5 text-cyan-400" />
              {t.riskReport.recommendations}
            </h3>
            <div className="space-y-2">
              {result.recommendations.map((rec, idx) => (
                <div
                  key={idx}
                  className="flex items-start space-x-3 p-3 rounded-xl bg-white/[0.02] border border-white/5 text-xs text-slate-300"
                >
                  <span className="w-5 h-5 rounded-full bg-cyan-500/20 text-cyan-400 flex items-center justify-center flex-shrink-0 text-[11px] font-bold">
                    {idx + 1}
                  </span>
                  <span className="leading-relaxed">{rec}</span>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Caution Notice */}
        <div className="mt-6 p-3 rounded-xl bg-blue-500/5 border border-blue-500/20 flex items-start space-x-2 text-[11px] text-blue-300">
          <Info className="w-4 h-4 flex-shrink-0 mt-0.5 text-blue-400" />
          <span>
            <strong>Safety Caution:</strong> {t.riskReport.disclaimer} Never classify an unknown
            message or link as definitively safe based only on an automated scan.
          </span>
        </div>
      </div>
    </motion.div>
  );
}

